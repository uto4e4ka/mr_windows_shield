def _build() -> dict[str, list[Question]]:
    bank = {}
    for original in QUESTIONS:
        topic = original.key
        items = [replace(original, id=f"{topic}00")]
        for number, item in enumerate(_TEXTS[topic], start=1):
            text, answers = item if isinstance(item, tuple) else (item, SCALE[topic])
            items.append(Question(topic, text, EMOJI[topic], answers, id=f"{topic}{number:02d}"))
        bank[topic] = items
    return bank


BANK = _build()
QUESTION_BY_ID = {q.id: q for items in BANK.values() for q in items}
ORIGINAL_IDS = [BANK[topic][0].id for topic in TOPICS]


def pick_questions(used: list[str], rng: random.Random | None = None) -> list[str]:
    """По одному непройденному вопросу на тему; тема пройдена целиком — круг заново."""
    rng = rng or random
    chosen = []
    for topic in TOPICS:
        ids = [q.id for q in BANK[topic]]
        fresh = [i for i in ids if i not in used] or ids
        chosen.append(rng.choice(fresh))
    return chosen


def mark_used(used: list[str], chosen: list[str]) -> list[str]:
    """Запомнить выбранные. Если тема уже пройдена по кругу — её история начинается заново."""
    result = list(used)
    for qid in chosen:
        ids = {q.id for q in BANK[QUESTION_BY_ID[qid].key]}
        if ids <= set(result):
            result = [i for i in result if i not in ids]
        result.append(qid)
    return result
